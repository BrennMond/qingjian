//! # stele-embed — 本地向量偏好记忆
//!
//! 中文职责：**从用户自己的历史里**学出一组低维整数向量，用它给候选加一个
//! 有界的偏好分。**不上网、不加载外部模型、不引入第三方依赖。**
//! English role: learn low-dimensional integer vectors from the user's own history
//! and use them to add a bounded preference bonus. Offline, model-free, zero-dep.
//! 架构位置：PLAN §2.1 的"侧挂服务"——注入引擎的 `Ranker` 链，不是引擎的上层。
//!
//! # 它凭什么算"向量记忆"
//!
//! 已有的两档记忆都是**精确查表**：
//!
//! | 档 | 键 | 什么时候生效 |
//! | --- | --- | --- |
//! | P4a `MemoryRanker` | 编码（`ni'hao`） | 这个编码**打过** |
//! | P4b 预测表 | 上下文（`微信`） | 这个搭配**打过** |
//!
//! 从没发生过的搭配，两档都无话可说。这里换一种记录方式：把
//! `(上下文词 → 下一个词)` 的计数**投影成向量**（[`model`]），
//! 于是"共同邻居"能带来泛化——`今天` 与 `明天` 都接 `天气`，
//! 那么即使 `后天 → 天气` 从没出现过，它也会被算得比无关词高一点。
//!
//! **这条泛化能力是这个 crate 存在的唯一理由。** 没有它，这里就只是
//! P4b 的一份昂贵复制品（收益问题见 `docs/embed-design.md` §"收益怎么证伪"）。
//!
//! # seam 的三个角色（PLAN §5.12 要求"顺手回答"）
//!
//! - **接口是什么**：`stele_core::Ranker`（以及内核的 `Candidate` / `Score`）。
//! - **谁实现**：本 crate（[`EmbedRanker`] + [`VectorMemory`]）。
//! - **谁消费**：引擎流水线在**装配时**把它塞进 `Services::rankers`，
//!   与 `stele_memory::MemoryRanker` 同一条链。引擎不知道它存在。
//!
//! # 默认关闭（D46）
//!
//! 它**不随默认配置生效**：装配处（CLI / 未来的前端）不给 `--embed`
//! 就不构造它，于是**默认行为逐字节可复现**——与 P4a 的 `--userdb`、
//! P4b 的 `--predict` 同一条产品决定。
//!
//! ## 内存上限（D46 的②要求：写进文档 **并** 打进称重台）
//!
//! 两张 `i16` 向量表：`词表大小 V × 维数 dim × 2 字节 × 2`。
//! 默认 `dim = 32`，而词表来自用户记忆的预测表（受 `DEFAULT_PREDICT_CAPACITY`
//! 约束，条目有上限、词数因此也有上限）：
//!
//! | 词表 V | dim=32 的两张表 | 说明 |
//! | --- | --- | --- |
//! | 5 000 | **0.6 MiB** | 轻度用户 |
//! | 20 000 | **2.4 MiB** | 重度用户（与预测表同量级） |
//! | 50 000 | **6.1 MiB** | 上界（预测表到不了这个规模） |
//!
//! 也就是说：**它小到不需要动用 D46 的例外**（默认配置仍在 30 MB 红线内）。
//! `VectorMemory::bytes()` 给出实测值，称重台把它打出来。
//!
//! # 明确不做的事
//!
//! - **不记录按键日志、不发网络请求**（PLAN §0.1 的第三根支柱）。
//!   学习的输入只有"上屏事件"里的文本与上下文——与 P4a/P4b 同一份。
//! - **不使用浮点**（D13）：投影是 ±1、累加是整数、量化是整数除法。
//! - **不生成候选**（PLAN §5.3 候选封闭）：只重排已产出的候选。

